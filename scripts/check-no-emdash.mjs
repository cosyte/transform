#!/usr/bin/env node
/**
 * scripts/check-no-emdash.mjs: the em-dash gate, over every tracked file.
 *
 * Run: `pnpm check:no-emdash`, or `pnpm check:no-emdash --stdin <label>` to hold
 * a piece of text that is not a file (a PR title, a PR body, a commit message)
 * to the same rule.
 *
 * THE RULE. Founder directive 2026-07-24, stated canonically in the
 * knowledgebase brand voice document: cosyte never uses the em dash. Not in a
 * file, not in a commit message, not in a PR title or body. Rewrite the sentence
 * with a period, a colon, a comma, or parentheses. NEVER re-encode the character:
 * the HTML entities, the percent-encoding and the JavaScript escapes are banned
 * on the same footing as the literal, and each has its own arm below.
 *
 * THIS GATE DID NOT ARRIVE ON A CLEAN TREE, AND THAT ORDERING IS THE POINT. The
 * same change swept 609 occurrences out of 73 of the 98 tracked files. A gate
 * landing before its sweep reds `main` on arrival; a sweep landing before its
 * gate grows the character back on the next session. They are one commit.
 *
 * ---------------------------------------------------------------------------
 * WHY THIS IS NODE AND NOT A SHELL SCRIPT
 * ---------------------------------------------------------------------------
 *
 * Every other scanner in this repository has had to defend itself against the
 * agent container's `grep`, which is a shell FUNCTION wrapping ugrep with
 * `-G --ignore-files --hidden -I` forced on. Two of those forced flags turn a
 * scanner into the exact defect it exists to close: `-I` skips a file it judges
 * binary, silently, at exit 0, and `--ignore-files` honours `.gitignore`. The
 * sibling gates answer that with `unset -f grep xargs sed awk` plus a probe.
 *
 * That answer works only for the names someone remembered to list. This gate
 * shells out for nothing at all. It reads bytes with `node:fs`; the only child
 * processes are `git ls-files` and `git check-attr`, and both have their exit
 * status checked rather than assumed. There is no pipeline here whose status can
 * be lost, which is the other half of the same class: `grep` exits 1 on no-match
 * and `xargs` reports that as 123, so "clean" and "died part way through" are
 * indistinguishable by exit code in the shell form.
 *
 * ---------------------------------------------------------------------------
 * WHY NOTHING IN THIS REPOSITORY IS EXCLUDED FROM THE SCAN BY PATH
 * ---------------------------------------------------------------------------
 *
 * A scanner that spells the forms it bans has to exclude itself, and a
 * self-exclusion is a demonstrated false green in a sibling repository: an em
 * dash appended to the gate script scanned OK, because the gate was the one file
 * nobody checked. The sibling's answer is to exclude the file from the encoded
 * arms and hold it to the literal one, which shrinks the hole rather than
 * closing it.
 *
 * There is no hole here, because there is nothing to exclude. EVERY spelling
 * below is ASSEMBLED at runtime from the codepoint `0x2014`, and the prose above
 * and below names the forms rather than writing them out, so this file contains
 * none of them as text. It is scanned exactly like every other tracked file, by
 * the same code path, with no special case anywhere. If you add an arm, assemble
 * it; do not paste a literal in, and do not answer a red here by adding an
 * exclusion.
 *
 * AND THE PROBE ENFORCES THAT RATHER THAN TRUSTING IT. `probe()` check 5b
 * reconciles the set of files this run SKIPPED against the set `.gitattributes`
 * DECLARES, path for path. A count check alone does not: a path exclusion that
 * pushes what it skips onto the declared-binary list balances the arithmetic,
 * and the outside-`vendor/` refusal reads the declaration and so never sees it.
 * A refuter demonstrated exactly that on this gate, in 34 characters, with every
 * test still green.
 *
 * ---------------------------------------------------------------------------
 * THE ONE EXEMPTION, WHICH IS A BOUNDARY RATHER THAN A FILE
 * ---------------------------------------------------------------------------
 *
 * `CHANGELOG.md` is scanned ABOVE `## Released before this file was generated`
 * and not below it. Everything above that heading is generated by the release
 * from a changeset summary, so an em dash there is a public-surface instance: a
 * changeset summary becomes the published release body AND a line in the
 * tarball's changelog. Everything below it is the hand-maintained history that
 * predates changelog generation, preserved verbatim when it was relocated, and
 * every entry is byte identical to its copy inside a published tarball. Editing
 * it would rewrite the evidence a changelog exists to hold, and
 * `test/scripts/changelog-generation.test.ts` measures that the archive comes
 * through a release byte identical.
 *
 * IT FAILS CLOSED. If the boundary heading disappears, the whole file is in
 * scope and this gate reds loudly, which is the correct direction: the
 * alternative is an exemption that silently grows to cover the generated half.
 *
 * ---------------------------------------------------------------------------
 * THE BINARY PARTITION IS A DECLARATION, NOT A HEURISTIC
 * ---------------------------------------------------------------------------
 *
 * A DEFLATE stream can contain `E2 80 94` by coincidence, and there is no edit
 * that removes a byte from a compressed stream. THE REPOSITORY TRACKS ONE SUCH
 * ARCHIVE TODAY: `vendor/cosyte-fhir-0.0.0.tgz`, a `pnpm pack` tarball of a
 * cosyte sibling, declared in `.gitattributes`, which is the whole of the
 * exemption; nothing else in the tree is declared. `vendor/cosyte-hl7-0.0.0.tgz`
 * sat beside it and carried exactly one such coincidence when it was measured;
 * it is gone, because `@cosyte/hl7` is a registry devDependency now rather than
 * a vendored tarball, and the declared set shrank with it.
 *
 * The partition is `git check-attr binary`, refused for any path outside
 * `vendor/`. It is deliberately NOT a NUL-byte test and deliberately not
 * `grep -I`'s heuristic: a sibling repo tracks a genuine UTF-8 TypeScript source
 * carrying a literal NUL that held 14 em dashes, and a NUL partition would have
 * skipped a prose-bearing source file in silence. A `.gitattributes` line is a
 * human declaration, so every skip is something someone wrote down and every red
 * has a defined one-line fix. Bounding it to `vendor/` keeps `*.ts binary` from
 * silencing this gate over the whole source tree from a dotfile.
 *
 * ---------------------------------------------------------------------------
 * KNOWN LIMITS, named rather than discovered later
 * ---------------------------------------------------------------------------
 *
 *  (i)   It matches U+2014 as UTF-8 and as the textual encodings listed below.
 *        It does NOT match an em dash in some other charset (a CP1252 `0x97`
 *        fixture, a UTF-16 document). Such a file scans clean and this gate
 *        stays green. There is none today; every tracked text file decodes as
 *        UTF-8.
 *  (ii)  The PCRE source spelling of the codepoint (a backslash, an `x`, and the
 *        hex in braces) is NOT banned as literal ASCII text. It is how a
 *        PCRE-based scanner names this codepoint. It renders as nothing;
 *        banning it would red a scanner for being a scanner.
 *  (iii) It reads file CONTENTS and file NAMES. It cannot see a PR title, body
 *        or commit message on its own: CI feeds those through `--stdin`. On a
 *        squash merge the PR title and body BECOME the commit message, so those
 *        are the same surface.
 *
 * Zero dependencies. Node builtins only.
 */

import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";

const ROOT = path.resolve(import.meta.dirname, "..");

/** U+2014, built from the codepoint so this file never spells the character. */
const EM = String.fromCodePoint(0x2014);
const EM_BYTES = Buffer.from(EM, "utf8");

const HEX = (0x2014).toString(16); // the four hex digits
const DEC = String(0x2014); // the four decimal digits

// The remaining spellings, assembled rather than written out, so that this file
// contains none of them as text and needs no exclusion from its own scan.
const PCT = [...EM_BYTES].map((b) => `%${b.toString(16).toUpperCase()}`).join("");
const AMP = "&";
const NAMED = `${AMP}mdash`;
const NUM = `${AMP}#`;
const BS = "\\";

/**
 * Every banned spelling, as [label, RegExp], each paired index-for-index with a
 * specimen built to contain exactly that spelling.
 *
 * THE ENCODED ARMS ARE NOT DECORATION. The reference sweep of this rule in a
 * sibling repository found the gate caught what the hand sweep missed precisely
 * because a manifest held the named HTML entity rather than the literal
 * character. Measured on this tree at the time of landing: 659 literal
 * occurrences and ZERO entity, percent or escape forms. The arms stay anyway;
 * the next contributor's editor may not agree with this one's.
 *
 * The three entity arms tolerate a missing semicolon, because HTML5 consumes the
 * named form and both numeric forms without one, and each carries a boundary so
 * that a longer digit run, a longer hex run, or a longer word (all of which mean
 * something else entirely) does not match. The numeric arms tolerate leading
 * zeros and either case, both of which are valid character references.
 *
 * The two JavaScript escape arms are case SENSITIVE on purpose: no language
 * spells this character with a capital `U` and four hex digits (JavaScript uses
 * a lowercase `u`, bare or braced; Python's capital form takes eight digits), so
 * a case-insensitive arm buys no true positive and reds an ordinary Windows path
 * that happens to contain a user directory of that name. Measured as a live
 * false positive in a sibling before it was split out.
 */
const PATTERNS = [
  ["the literal character", new RegExp(EM, "g")],
  ["the percent-encoding", new RegExp(PCT, "gi")],
  ["the named HTML entity", new RegExp(`${NAMED}(?:;|(?![A-Za-z0-9]))`, "gi")],
  ["the decimal character reference", new RegExp(`${NUM}0*${DEC}(?:;|(?![0-9]))`, "gi")],
  ["the hex character reference", new RegExp(`${NUM}[xX]0*${HEX}(?:;|(?![0-9A-Fa-f]))`, "g")],
  ["the JavaScript escape", new RegExp(`${BS}${BS}u${HEX}`, "g")],
  ["the braced JavaScript escape", new RegExp(`${BS}${BS}u${BS}{0*${HEX}${BS}}`, "g")],
];

const SPECIMENS = [
  `a${EM}b`,
  `a${PCT}b`,
  `a${NAMED};b`,
  `a${NUM}${DEC};b`,
  `a${NUM}x${HEX};b`,
  `a${BS}u${HEX}b`,
  `a${BS}u{${HEX}}b`,
];

const CHANGELOG = "CHANGELOG.md";
const CHANGELOG_BOUNDARY = "## Released before this file was generated";

/** Every occurrence of every banned spelling in `text`, with a locus. */
function findEmDashes(text) {
  const hits = [];
  const lines = text.split("\n");
  for (const [label, re] of PATTERNS) {
    for (let i = 0; i < lines.length; i++) {
      re.lastIndex = 0;
      let m;
      while ((m = re.exec(lines[i])) !== null) {
        hits.push({
          line: i + 1,
          column: m.index + 1,
          label,
          excerpt: lines[i].slice(Math.max(0, m.index - 40), m.index + 40).trim(),
        });
        if (m[0].length === 0) re.lastIndex++;
      }
    }
  }
  return hits;
}

function git(args) {
  const r = spawnSync("git", args, {
    cwd: ROOT,
    encoding: "buffer",
    maxBuffer: 128 * 1024 * 1024,
  });
  if (r.error) throw new Error(`could not run git ${args[0]}: ${r.error.message}`);
  if (r.status !== 0) {
    throw new Error(`git ${args[0]} exited ${r.status}: ${r.stderr?.toString("utf8").trim()}`);
  }
  return r.stdout;
}

/** Every tracked path, NUL separated so a newline in a name cannot split one. */
function trackedFiles() {
  return git(["ls-files", "-z"])
    .toString("utf8")
    .split("\0")
    .filter((p) => p.length > 0);
}

/**
 * Paths declared `binary` in `.gitattributes`. A declaration outside `vendor/`
 * is refused rather than honoured: an exclusion that reaches source or
 * documentation silences this gate with nothing saying so.
 */
function declaredBinary(files) {
  const stdin = Buffer.from(files.join("\0") + "\0", "utf8");
  const r = spawnSync("git", ["check-attr", "--stdin", "-z", "binary"], {
    cwd: ROOT,
    input: stdin,
    encoding: "buffer",
    maxBuffer: 128 * 1024 * 1024,
  });
  if (r.error) throw new Error(`could not run git check-attr: ${r.error.message}`);
  if (r.status !== 0) {
    throw new Error(`git check-attr exited ${r.status}: ${r.stderr?.toString("utf8").trim()}`);
  }
  const fields = r.stdout.toString("utf8").split("\0");
  const out = new Set();
  for (let i = 0; i + 2 < fields.length; i += 3) {
    if (fields[i + 2] === "set") out.add(fields[i]);
  }
  return out;
}

function refuse(why, detail) {
  console.error(`[no-emdash] REFUSED: ${why}`);
  console.error(`            ${detail}`);
  console.error("            Refusing to report a clean tree on a scanner that cannot see.");
  process.exit(1);
}

function fail(what, hits) {
  console.error("");
  for (const h of hits) {
    console.error(`[no-emdash] FAIL  ${h.where}:${h.line}:${h.column}  (${h.label})`);
    console.error(`              ${h.excerpt}`);
  }
  console.error(
    `\n[no-emdash] ${hits.length} occurrence(s) in ${what}, across ` +
      `${new Set(hits.map((h) => h.where)).size} location(s).`,
  );
  console.error("[no-emdash] cosyte never uses em dashes (founder directive, 2026-07-24).");
  console.error(
    "[no-emdash] Rewrite with a period, a colon, a comma, or parentheses. " +
      "Never re-encode the character.",
  );
  process.exit(1);
}

/**
 * Refuse to report a clean tree on a scanner that cannot see.
 *
 * Each assertion closes a way this gate could return "no findings" having
 * examined nothing. A probe that only proved the patterns compile would miss
 * every one of them after the second.
 */
function probe({ files, scanned, binary, binarySet, bytesRead, archiveHits, hasArchive }) {
  // 1. GROUND TRUTH. Everything above is derived from one codepoint constant, so
  //    the patterns and the specimens would agree with each other even if that
  //    constant were wrong. Anchor it on the bytes: U+2014 is E2 80 94 in UTF-8,
  //    and that is not a fact this repository gets to define.
  if (!EM_BYTES.equals(Buffer.from([0xe2, 0x80, 0x94]))) {
    refuse(
      "the character being scanned for is not U+2014",
      `built bytes ${[...EM_BYTES].map((b) => b.toString(16)).join(" ")}, expected e2 80 94.`,
    );
  }

  // 2. Every pattern matches a specimen built to contain exactly its spelling,
  //    and the two lists are index aligned by contract.
  if (SPECIMENS.length !== PATTERNS.length) {
    refuse(
      "the specimen list and the pattern list are different lengths",
      "they are index aligned by contract; one was edited without the other.",
    );
  }
  for (let i = 0; i < PATTERNS.length; i++) {
    const [label, re] = PATTERNS[i];
    re.lastIndex = 0;
    if (!re.test(SPECIMENS[i])) {
      refuse(
        `the pattern for ${label} does not match its own specimen`,
        "one of them built wrong.",
      );
    }
  }

  // 3. THE SYNTHETIC CANARY. Checks 1 and 2 prove the PATTERNS are right.
  //    Neither of them runs `findEmDashes`, which is the function that actually
  //    scans a file, so a `findEmDashes` returning an empty array for every
  //    input would sail past both and report a clean tree.
  for (const specimen of SPECIMENS) {
    if (findEmDashes(specimen).length === 0) {
      refuse(
        `the scanner found nothing in a buffer built to contain ${JSON.stringify(specimen)}`,
        "findEmDashes is blind; every clean result in this run would be worthless.",
      );
    }
  }

  // 4. THE ON-DISK CANARY, which is the stronger one because it comes off a real
  //    file through the real read path. The CHANGELOG archive below the boundary
  //    is KNOWN to hold occurrences and is a frozen dated record, so a scan that
  //    reports it clean has gone blind rather than found good news. This is not
  //    the canary the gate depends on (see 3, which cannot be emptied): if the
  //    archive is ever legitimately rewritten, REPLACE this check, do not delete
  //    it.
  //
  //    ONLY WHEN THERE IS AN ARCHIVE. With the boundary heading gone there is no
  //    archive to be blind to, and the whole file is in scope and reds on its own
  //    findings. Enforcing the canary there would replace a precise "here is the
  //    occurrence" red with a misleading "the scanner cannot see" one.
  if (hasArchive && archiveHits === 0) {
    refuse(
      "the CHANGELOG archive below its boundary reported zero occurrences",
      "it is a frozen dated record known to contain them; the scanner is not seeing its subject.",
    );
  }

  // 5. Enumeration returned a tree. An empty or tiny `git ls-files` (wrong cwd, a
  //    filtered tool) must not read as a clean repository.
  //
  //    THE FLOOR IS 80 AND IT IS DELIBERATELY NOT THE CURRENT COUNT. This repo
  //    tracked 103 paths when this landed, so the floor leaves room to delete a
  //    module without turning the refusal into a chore. Set it near the count
  //    and every ordinary deletion reads as a filtered enumeration; set it at
  //    zero and there is no floor at all.
  if (files.length < 80) {
    refuse(
      `git ls-files returned only ${files.length} path(s)`,
      "this repo tracks a hundred or so files; the enumeration is filtered or wrong.",
    );
  }
  if (scanned.length === 0) refuse("every tracked file was excluded", "nothing was scanned.");
  if (scanned.length + binary.length !== files.length) {
    refuse(
      `the partition lost files: ${scanned.length} scanned + ${binary.length} declared binary is not ${files.length} tracked`,
      "every tracked path must be classified exactly once, or the scan has a silent gap.",
    );
  }

  // 5b. THE SKIPPED SET IS THE DECLARED SET, PATH FOR PATH, NOT MERELY THE SAME
  //     SIZE. The arithmetic above balances for a path exclusion that ACCOUNTS
  //     for what it skipped, and the outside-`vendor/` refusal cannot see one
  //     either, because that reads the declaration rather than the skip list. A
  //     refuter built exactly that here: adding `|| rel.startsWith("docs-content/")`
  //     to the skip condition hid seven published documentation pages, printed a
  //     clean banner, and left all 38 tests green. The only tell was a count
  //     nothing asserted. So the two are reconciled: the ONLY thing that may skip
  //     a file's content is a `.gitattributes` declaration.
  const undeclared = binary.filter((p) => !binarySet.has(p));
  if (undeclared.length > 0 || binary.length !== binarySet.size) {
    const shown = (undeclared.length > 0 ? undeclared : binary).slice(0, 5);
    refuse(
      `${String(undeclared.length || binary.length)} path(s) were skipped without a 'binary' declaration`,
      `the only thing that may skip a file's CONTENT is .gitattributes: ${shown.join(", ")}`,
    );
  }
  if (bytesRead === 0) refuse("the scan read zero bytes", "no file was opened.");

  // 6. Files known to be text ARE in the scanned set. A tool honouring
  //    .gitignore, or a misfiring binary heuristic, drops real files silently.
  for (const known of [
    "README.md",
    "package.json",
    "src/index.ts",
    "scripts/check-no-emdash.mjs",
  ]) {
    if (!scanned.includes(known)) {
      refuse(
        `${known} is not in the scanned set`,
        "it is tracked and it is text, so the enumeration or the partition is dropping files.",
      );
    }
  }
}

function scanStdin(label) {
  const text = readFileSync(0, "utf8");
  const hits = findEmDashes(text).map((h) => ({ ...h, where: label }));
  // The synthetic canary runs here too: this mode reads no repository file, so
  // nothing else in this run would prove the scanner can see.
  for (const specimen of SPECIMENS) {
    if (findEmDashes(specimen).length === 0) {
      refuse("the scanner found nothing in a buffer built to be dirty", "findEmDashes is blind.");
    }
  }
  if (hits.length) fail(label, hits);
  console.log(`[no-emdash] OK: no em dashes in ${label} (${text.length} bytes read).`);
}

function scanTree() {
  const files = trackedFiles();
  const binarySet = declaredBinary(files);

  const outside = [...binarySet].filter((p) => !p.startsWith("vendor/"));
  if (outside.length) {
    console.error(outside.map((p) => `  ${p}`).join("\n"));
    console.error(
      "\n[no-emdash] The path(s) above are declared 'binary' in .gitattributes and are\n" +
        "            OUTSIDE vendor/, so they would be excluded from the content scan.\n" +
        "            That exclusion is for vendored third-party archives only. Move the\n" +
        "            file under vendor/, drop the declaration, or widen the rule in this\n" +
        "            script deliberately.",
    );
    process.exit(1);
  }

  // A tracked FILENAME can itself hold the character, and scanning contents never
  // looks at one. This arm covers EVERY tracked path, declared binaries included:
  // a declaration about a file's BYTES says nothing about its NAME.
  const nameHits = [];
  for (const rel of files) {
    for (const h of findEmDashes(rel)) nameHits.push({ ...h, where: `tracked filename ${rel}` });
  }
  if (nameHits.length) fail("a tracked FILENAME (not its contents)", nameHits);

  const scanned = [];
  const binary = [];
  const hits = [];
  let bytesRead = 0;
  let archiveHits = 0;
  // Whether an archive exists at all. The canary in `probe()` asserts the archive
  // is never reported clean, and with no boundary heading there IS no archive, so
  // enforcing it in that branch would preempt the findings and report blindness
  // instead of the hits the gate just collected. That branch already reds, on the
  // hits themselves, which is the more useful red.
  let hasArchive = false;

  for (const rel of files) {
    if (binarySet.has(rel)) {
      binary.push(rel);
      continue;
    }
    scanned.push(rel);
    let buf;
    try {
      buf = readFileSync(path.join(ROOT, rel));
    } catch (err) {
      // Fail closed: a tracked file this gate cannot open is not a clean file.
      console.error(`[no-emdash] FAIL  ${rel}: could not read (${err.message})`);
      console.error("[no-emdash] A tracked file this gate cannot open is a failure, never a skip.");
      process.exit(1);
    }
    bytesRead += buf.length;
    const text = buf.toString("utf8");

    if (rel === CHANGELOG) {
      const idx = text.indexOf(`\n${CHANGELOG_BOUNDARY}`);
      const head = idx === -1 ? text : text.slice(0, idx + 1);
      const tail = idx === -1 ? "" : text.slice(idx + 1);
      hasArchive = idx !== -1;
      archiveHits = findEmDashes(tail).length;
      if (idx === -1) {
        console.error(
          `[no-emdash] ${CHANGELOG} has no '${CHANGELOG_BOUNDARY}' heading, so ALL of it is\n` +
            "            in scope. This gate fails closed rather than widening an exemption.",
        );
      }
      for (const h of findEmDashes(head)) hits.push({ ...h, where: rel });
      continue;
    }

    for (const h of findEmDashes(text)) hits.push({ ...h, where: rel });
  }

  probe({ files, scanned, binary, binarySet, bytesRead, archiveHits, hasArchive });

  if (hits.length) fail("the tracked files listed above", hits);

  console.log(
    `[no-emdash] OK: ${scanned.length} tracked file(s) scanned (${bytesRead} bytes), ` +
      `${binary.length} declared binary and exempt from the content scan, ` +
      `${files.length} filename(s) checked.`,
  );
  console.log(
    `[no-emdash]     ${CHANGELOG} scanned above '${CHANGELOG_BOUNDARY}'; the ` +
      `${archiveHits} occurrence(s) in the dated archive below it are out of scope and are ` +
      "this run's on-disk canary.",
  );
}

function main() {
  const argv = process.argv.slice(2);
  if (argv[0] === "--stdin") {
    scanStdin(argv[1] ?? "stdin");
    return;
  }
  if (argv.length) {
    console.error(`[no-emdash] unknown argument: ${argv[0]}`);
    console.error("[no-emdash] usage: check-no-emdash.mjs [--stdin <label>]");
    process.exit(1);
  }
  scanTree();
}

try {
  main();
} catch (err) {
  console.error("[no-emdash] FAILED:", err.message);
  process.exit(1);
}
